"""Extract the LLM-evaluation data embedded in the study's website into CSVs.

The "LLM Evaluations" panel (llm_evals.py, static/llm.js) shows the results of
Nguyen, Watts & Whiting (2026), "A Large-Scale Evaluation of Commonsense
Knowledge in Humans and Large Language Models", PNAS Nexus 5(3): pgag029.
Its standalone website, llm-evals.html (commonsense-platform/client/public/),
inlines every number as JavaScript constants; it is generated by
website/generate.py in the study's open-llm-commonsense-eval repo. This script
reads those constants and writes, under this directory:

    data/llm_evals/models.csv                   one row per model: its scores as a
                                                survey respondent and the share of
                                                participants it beats
    data/llm_evals/statements.csv               statement text, source, category,
                                                the six properties, and the share
                                                of participants answering yes
    data/llm_evals/statement_scores.csv         statement commonsensicality among
                                                participants ("humans") and in each
                                                model's simulated population
    data/llm_evals/model_ratings/<model>.csv    a model's P(yes) to both questions
    data/llm_evals/participants.csv             each participant's scores
    data/llm_evals/participant_ratings.csv      each participant's 50 answers
    static/llm-evals-overview.svg               the figure of the three settings

The page stores the platform's raw property flags (opinion, behavior,
figure_of_speech, judgment, reasoning, everyday). They are converted to this
app's vocabulary (PROP_DEFS in static/app.js), which is the opposite polarity
for all but everyday, as in statement-generation/gap_analysis.py. The page's
own labels for figure_of_speech and reasoning are inverted, so its filters
show those two the wrong way round.

Stdlib only. Rerun when the website is regenerated, from any directory:
    python .scripts/visualize/extract_llm_evals.py path/to/llm-evals.html
"""
import argparse
import csv
import json
import re
import shutil
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent
OUT_DIR = BASE_DIR / "data" / "llm_evals"
FIGURE_PATH = BASE_DIR / "static" / "llm-evals-overview.svg"

CONSTANTS = [
    "SUBJECTS", "SUBJ_RATINGS", "STMT_TEXTS", "STMT_SRCS", "STMT_CATS", "STMT_DIMS",
    "SCORE_COLS", "STMT_SCORES", "STMT_AVGS", "MODELS", "MODEL_RATINGS", "MODEL_VS_HUMANS",
]
# STMT_DIMS order (generate.py) -> (app property, invert)
DIMS = [
    ("judgment", "positive", True),
    ("behavior", "physical", True),
    ("figure_of_speech", "literal_language", True),
    ("opinion", "fact", True),
    ("reasoning", "knowledge", True),
    ("everyday", "everyday", False),
]
PROP_COLS = ["fact", "physical", "literal_language", "positive", "knowledge", "everyday"]


def read_constants(html: str) -> dict:
    data = {}
    for match in re.finditer(r"^const ([A-Z_]+) = (.*);\s*$", html, re.MULTILINE):
        if match.group(1) in CONSTANTS:
            data[match.group(1)] = json.loads(match.group(2))
    missing = [name for name in CONSTANTS if name not in data]
    if missing:
        raise SystemExit(f"Constants not found in the page: {', '.join(missing)}")
    return data


def write_csv(path: Path, header: list, rows) -> None:
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(header)
        writer.writerows(rows)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("html", type=Path, help="path to llm-evals.html")
    args = parser.parse_args()
    html = args.html.read_text(encoding="utf-8")
    d = read_constants(html)

    n_stmts = len(d["STMT_TEXTS"])
    models = d["MODELS"]
    by_name = {m["name"]: m["id"] for m in models}
    assert all(len(d[k]) == n_stmts for k in ("STMT_SRCS", "STMT_CATS", "STMT_DIMS", "STMT_SCORES", "STMT_AVGS"))
    assert d["SCORE_COLS"][0] == "humans" and set(d["SCORE_COLS"][1:]) == set(by_name)
    assert set(d["MODEL_RATINGS"]) == set(by_name.values()) and set(d["MODEL_VS_HUMANS"]) == set(by_name)

    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    (OUT_DIR / "model_ratings").mkdir(parents=True)

    write_csv(
        OUT_DIR / "models.csv",
        ["model_id", "model", "consensus", "awareness", "commonsensicality", "human_percentile"],
        ([m["id"], m["name"], *m["scores"], d["MODEL_VS_HUMANS"][m["name"]]] for m in models),
    )

    def props(dims):
        values = {col: (1 - dims[i] if invert else dims[i]) for i, (_, col, invert) in enumerate(DIMS)}
        return [values[col] for col in PROP_COLS]

    write_csv(
        OUT_DIR / "statements.csv",
        ["statement_id", "statement", "source", "category", *PROP_COLS, "I_agree_mean", "others_agree_mean"],
        (
            [i, d["STMT_TEXTS"][i], d["STMT_SRCS"][i], d["STMT_CATS"][i], *props(d["STMT_DIMS"][i]), *d["STMT_AVGS"][i]]
            for i in range(n_stmts)
        ),
    )

    score_ids = ["humans"] + [by_name[name] for name in d["SCORE_COLS"][1:]]
    order = ["humans"] + [m["id"] for m in models]
    cols = [score_ids.index(c) for c in order]
    write_csv(
        OUT_DIR / "statement_scores.csv",
        ["statement_id", *order],
        ([i, *(row[c] for c in cols)] for i, row in enumerate(d["STMT_SCORES"])),
    )

    for m in models:
        write_csv(
            OUT_DIR / "model_ratings" / f"{m['id']}.csv",
            ["statement_id", "I_agree", "others_agree"],
            ([i, *pair] for i, pair in enumerate(d["MODEL_RATINGS"][m["id"]])),
        )

    write_csv(
        OUT_DIR / "participants.csv",
        ["participant_id", "consensus", "awareness", "commonsensicality"],
        d["SUBJECTS"],
    )
    write_csv(
        OUT_DIR / "participant_ratings.csv",
        ["participant_id", "statement_id", "I_agree", "others_agree"],
        ([pid, *rating] for pid, ratings in enumerate(d["SUBJ_RATINGS"]) for rating in ratings),
    )

    svg = re.search(r'<div id="overview-diagram">\s*(<svg.*?</svg>)', html, re.DOTALL)
    if svg:
        # Drop the inline sizing so the file scales to whatever <img> holds it
        figure = re.sub(r'\s(width|height|style)="[^"]*"', "", svg.group(1).split(">", 1)[0], count=3)
        FIGURE_PATH.write_text(figure + ">" + svg.group(1).split(">", 1)[1] + "\n", encoding="utf-8")

    print(f"{len(models)} models, {n_stmts} statements, {len(d['SUBJECTS'])} participants -> {OUT_DIR}")


if __name__ == "__main__":
    main()
